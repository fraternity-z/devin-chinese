# -*- coding: utf-8 -*-
"""In-place patch the installed MS-CEINTL zh-hans pack for Devin.

Merges zh_patch.json into the pack's main.i18n.json and ext_patch.json into
extension i18n files, registers the new js-debug-companion translation id in
package.json + languagepacks.json, then clears the generated NLS cache so
translations are rebuilt on next Devin start.

Idempotent: backups (.devin-zh.bak) are made once before first modification.
Run AFTER Devin is closed, then restart Devin.
"""
import glob
import json
import os
import shutil
import sys

from _paths import PACK_DIR, TRANSLATIONS_DIR

EXT_HOME = os.path.join(os.path.expanduser("~"), ".devin", "extensions")
NEW_EXT_ID = "ms-vscode.js-debug-companion"
NEW_EXT_FILE = "ms-vscode.js-debug-companion.i18n.json"


def load(p):
    return json.load(open(p, encoding="utf-8"))


def dump(d, p):
    json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


def backup_once(p):
    bak = p + ".devin-zh.bak"
    if not os.path.exists(bak):
        shutil.copy2(p, bak)
        print(f"  backup -> {os.path.basename(bak)}")


def find_pack():
    if os.environ.get("VSCODE_ZH_PACK"):
        return str(PACK_DIR)
    cands = sorted(glob.glob(os.path.join(
        EXT_HOME, "ms-ceintl.vscode-language-pack-zh-hans-*")))
    if not cands:
        sys.exit("ms-ceintl zh-hans pack not found under " + EXT_HOME)
    return cands[-1]


def main():
    pack = find_pack()
    print("patching:", pack)
    zh = load(TRANSLATIONS_DIR / "core" / "zh_patch.json")
    ext = load(TRANSLATIONS_DIR / "extensions" / "ext_patch.json")

    # 1. main.i18n.json
    main_p = os.path.join(pack, "translations", "main.i18n.json")
    backup_once(main_p)
    m = load(main_p)
    n = 0
    for mod, km in zh.items():
        c = m["contents"].setdefault(mod, {})
        for k, v in km.items():
            if c.get(k) != v:
                c[k] = v
                n += 1
    dump(m, main_p)
    print(f"  main.i18n.json: {n} keys written")

    # 2. extension i18n files
    ext_dir = os.path.join(pack, "translations", "extensions")
    for eid, sections in ext.items():
        fp = os.path.join(ext_dir, eid + ".i18n.json")
        if os.path.exists(fp):
            backup_once(fp)
            d = load(fp)
        else:
            d = {"": ["Generated by devin-chinese install"],
                 "version": "1.0.0", "contents": {}}
        cnt = 0
        for sec, kv in sections.items():
            c = d["contents"].setdefault(sec, {})
            for k, v in kv.items():
                if c.get(k) != v:
                    c[k] = v
                    cnt += 1
        dump(d, fp)
        print(f"  {eid}.i18n.json: {cnt} keys written")

    # 3. package.json: register companion id
    pkg_p = os.path.join(pack, "package.json")
    backup_once(pkg_p)
    pkg = load(pkg_p)
    tr = pkg["contributes"]["localizations"][0]["translations"]
    if not any(t["id"] == NEW_EXT_ID for t in tr):
        tr.append({"id": NEW_EXT_ID,
                   "path": "./translations/extensions/" + NEW_EXT_FILE})
        json.dump(pkg, open(pkg_p, "w", encoding="utf-8"),
                  ensure_ascii=False, indent="\t")
        print("  package.json: registered", NEW_EXT_ID)

    # 4. languagepacks.json: add the new translation id
    lp_p = os.path.join(os.environ.get("APPDATA", ""), "Devin",
                        "languagepacks.json")
    if os.path.exists(lp_p):
        backup_once(lp_p)
        lp = load(lp_p)
        trs = lp.get("zh-cn", {}).get("translations", {})
        if NEW_EXT_ID not in trs:
            trs[NEW_EXT_ID] = os.path.join(ext_dir, NEW_EXT_FILE)
            dump(lp, lp_p)
            print("  languagepacks.json: added", NEW_EXT_ID)

    # 5. clear generated NLS cache (regenerates on next start)
    clp = os.path.join(os.environ.get("APPDATA", ""), "Devin", "clp")
    if os.path.isdir(clp):
        shutil.rmtree(clp, ignore_errors=True)
        print("  cleared", clp)

    print("\nDone. Restart Devin to apply.")


if __name__ == "__main__":
    main()
