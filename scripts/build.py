# -*- coding: utf-8 -*-
"""Build a standalone Devin zh-hans language pack.

Output:
  dist/devin-language-pack-zh-hans/           - extension directory
  dist/devin-zh.devin-language-pack-zh-hans-<ver>.vsix

Contents = official MS-CEINTL pack + zh_patch.json (core keys)
         + ext_patch.json (extension keys) + js-debug-companion file.
"""
import json
import os
import re
import shutil
import zipfile

from _paths import DIST_DIR, PACK_DIR, TRANSLATIONS_DIR

OUT_DIR = os.path.join(DIST_DIR, "devin-language-pack-zh-hans")
# NOTE: publisher sorts after "ms-ceintl" alphabetically so that, when both
# packs are installed, this pack wins per-translation-id merge order.
PUBLISHER = "zzdevin"
NAME = "devin-language-pack-zh-hans"
VERSION = "1.126.0"

NEW_EXT_ID = "ms-vscode.js-debug-companion"
NEW_EXT_PATH = "./translations/extensions/ms-vscode.js-debug-companion.i18n.json"


def load(p):
    return json.load(open(p, encoding="utf-8"))


def main():
    zh = load(TRANSLATIONS_DIR / "core" / "zh_patch.json")
    ext = load(TRANSLATIONS_DIR / "extensions" / "ext_patch.json")
    if os.path.exists(OUT_DIR):
        shutil.rmtree(OUT_DIR)

    # --- package.json ---
    pkg = load(os.path.join(PACK_DIR, "package.json"))
    pkg["name"] = NAME
    pkg["publisher"] = PUBLISHER
    pkg["version"] = VERSION
    pkg["displayName"] = "Chinese (Simplified) (简体中文) Language Pack for Devin"
    pkg["description"] = ("Language pack for Devin (based on the VS Code Chinese "
                          "Simplified pack, plus Devin-specific strings)")
    pkg.pop("__metadata", None)
    pkg.pop("scripts", None)
    loc = pkg["contributes"]["localizations"][0]
    loc["translations"] = [t for t in loc["translations"] if t["id"] != NEW_EXT_ID]
    loc["translations"].append({"id": NEW_EXT_ID, "path": NEW_EXT_PATH})

    # --- copy whole pack, then overlay ---
    shutil.copytree(PACK_DIR, OUT_DIR,
                    ignore=shutil.ignore_patterns(".vsixmanifest", "*.devin-zh.bak"))
    pkg_path = os.path.join(OUT_DIR, "package.json")
    json.dump(pkg, open(pkg_path, "w", encoding="utf-8"),
              ensure_ascii=False, indent="\t")

    # core: merge zh patch into main.i18n.json
    main_path = os.path.join(OUT_DIR, "translations", "main.i18n.json")
    main_i18n = load(main_path)
    for mod, km in zh.items():
        main_i18n["contents"].setdefault(mod, {}).update(km)
    json.dump(main_i18n, open(main_path, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    # extensions: merge bundle/package sections
    ext_dir = os.path.join(OUT_DIR, "translations", "extensions")
    for eid, sections in ext.items():
        fp = os.path.join(ext_dir, eid + ".i18n.json")
        if os.path.exists(fp):
            d = load(fp)
        else:
            d = {"": ["Generated by devin-chinese build"],
                 "version": "1.0.0", "contents": {}}
        for sec, kv in sections.items():
            d["contents"].setdefault(sec, {}).update(kv)
        json.dump(d, open(fp, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)

    # --- vsix ---
    vsix = os.path.join(DIST_DIR,
                        f"{PUBLISHER}.{NAME}-{VERSION}.vsix")
    manifest = f'''<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011">
  <Metadata>
    <Identity Language="en-US" Id="{NAME}" Version="{VERSION}" Publisher="{PUBLISHER}"/>
    <DisplayName>{pkg["displayName"]}</DisplayName>
    <Description xml:space="preserve">{pkg["description"]}</Description>
    <Tags>chinese,simplified,zh-cn,devin</Tags>
    <Categories>Languages</Categories>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="^1.126.0"/>
      <Property Id="Microsoft.VisualStudio.Code.LocalizedLanguages" Value="zh-cn"/>
    </Properties>
  </Metadata>
  <Installation><InstallationTarget Id="Microsoft.VisualStudio.Code"/></Installation>
  <Dependencies/>
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true"/>
  </Assets>
</PackageManifest>
'''
    ctypes = '''<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json"/>
  <Default Extension=".vsixmanifest" ContentType="text/xml"/>
  <Default Extension=".png" ContentType="image/png"/>
  <Default Extension=".md" ContentType="text/markdown"/>
</Types>
'''
    with zipfile.ZipFile(vsix, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", ctypes)
        z.writestr("extension.vsixmanifest", manifest)
        for root, _, fns in os.walk(OUT_DIR):
            for fn in fns:
                if fn.endswith(".devin-zh.bak"):
                    continue
                fp = os.path.join(root, fn)
                arc = os.path.join("extension",
                                   os.path.relpath(fp, OUT_DIR))
                z.write(fp, arc.replace(os.sep, "/"))
    print(f"built {vsix}")
    n = sum(len(v) for v in zh.values())
    print(f"core patched keys: {n}, ext patched keys: "
          f"{sum(len(s) for v in ext.values() for s in v.values())}")


if __name__ == "__main__":
    main()
